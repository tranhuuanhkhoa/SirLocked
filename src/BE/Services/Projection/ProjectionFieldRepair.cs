using System.Text.Json.Nodes;
using System.Text.RegularExpressions;
using SirLocked.Api.DTOs.Case;
using SirLocked.Api.Services.PuzzleKinds;

namespace SirLocked.Api.Services.Projection;

/// <summary>Builds a patch schema from the actual validator paths and the projection's writable fields.</summary>
internal static class ProjectionFieldRepair
{
    public const string Version = "projection-field-repair-v1";
    private static readonly Dictionary<string, string> Sections = new(StringComparer.Ordinal)
    {
        ["stage"] = "stages", ["scene"] = "scenes", ["character"] = "characters",
        ["item"] = "items", ["clue"] = "clues", ["dialogue"] = "dialogues",
        ["testimony"] = "testimonyFragments", ["challenge"] = "evidenceChallenges",
        ["conversation"] = "conversationNodes", ["puzzle"] = "puzzles", ["hint"] = "hints",
        ["interaction"] = "interactions", ["deduction"] = "deductions"
    };

    public static IReadOnlyList<string[]> Paths(JsonObject schema, CaseValidationResult validation)
    {
        var paths = new List<string[]>();
        foreach (var error in validation.Errors)
        {
            var path = ResolvePath(error);
            if (path is not null && IsWritable(schema, path)
                && !paths.Any(existing => existing.SequenceEqual(path)))
                paths.Add(path);
        }
        return paths;
    }

    public static IReadOnlyList<string[]> BlindPaths(JsonObject schema, IEnumerable<string> relatedIds)
    {
        var affected = relatedIds.ToHashSet(StringComparer.Ordinal);
        var visibleFields = new Dictionary<string, string[]>
        {
            ["clues"] = ["content", "narrativeMeaning", "inventoryDescription"],
            ["dialogues"] = ["answer"], ["testimonyFragments"] = ["text"],
            ["conversationNodes"] = ["lines"], ["deductions"] = ["prompt", "successResponse"],
            ["evidenceChallenges"] = ["successResponse"], ["items"] = ["inspectText"]
        };
        return visibleFields.SelectMany(section => affected.SelectMany(id =>
                section.Value.Select(field => new[] { section.Key, id, field })))
            .Where(path => IsWritable(schema, path)).ToArray();
    }

    public static string[] AffectedChallenges(GameplayProjectionPlan plan, IReadOnlyList<string[]> paths)
    {
        bool Changes(string section, string id) => paths.Any(path => path[0] == section && path[1] == id);
        var itemIds = plan.Skeleton.Clues.Where(clue => Changes("items", clue.Source)).Select(clue => clue.ClueId)
            .ToHashSet(StringComparer.Ordinal);
        return plan.Challenges.Where(pair =>
                Changes("evidenceChallenges", pair.Key) || Changes("dialogues", pair.Value.DialogueId)
                || pair.Value.CandidateEvidenceIds.Any(id => itemIds.Contains(id) || Changes("clues", id))
                || plan.TestimonyFragments.Any(fragment => fragment.Value.DialogueId == pair.Value.DialogueId
                    && Changes("testimonyFragments", fragment.Key)))
            .Select(pair => pair.Key).ToArray();
    }

    private static string[]? ResolvePath(CaseValidationError error)
    {
        var path = error.Path;
        // The compiler reports the detailed path inside its message.
        if (error.Code == "PROJECTION_CONTENT_MISMATCH")
        {
            var match = Regex.Match(error.Message, @"^PROJECTION_[A-Z_]+ ([\w.:-]+)(?:: |\.$|$)");
            if (!match.Success) return null;
            path = match.Groups[1].Value;
        }
        if (path.StartsWith("$.", StringComparison.Ordinal)) path = path[2..];
        var parts = path.Split('.');
        var owner = parts[0].Split(':', 2);
        if (owner.Length == 2 && Sections.TryGetValue(owner[0], out var section))
            parts = [section, owner[1], .. parts.Skip(1)];

        // Runtime puzzle params are generated by the server. Map only the portion authored by the model.
        if (parts is ["puzzles", var puzzle, "params", var key, ..]
            && PuzzleKindAuthoring.FreeKinds.Concat(PuzzleKindAuthoring.TruthBoundKinds)
                .Any(kind => PuzzleKindAuthoring.AllowedAuthoredKeys(kind).Contains(key)))
            return ["puzzles", puzzle, "authored", key];
        // A validator can report an index in a runtime array, while projection rows use stable IDs.
        if (parts[0].Contains('[') && !string.IsNullOrWhiteSpace(error.RefId))
            parts = [parts[0][..parts[0].IndexOf('[')], error.RefId, .. parts.Skip(1)];
        return parts.Length > 1 ? parts : null;
    }

    public static bool IsWritable(JsonObject schema, string[] path)
    {
        JsonNode? node = schema;
        for (var index = 0; index < path.Length; index++)
            node = ChildSchema(node, path, index);
        return node is JsonObject field && !field.ContainsKey("const") && !HasLockedChildren(field);
    }

    private static JsonNode? ChildSchema(JsonNode? parent, string[] path, int index)
    {
        if (path is ["puzzles", _, "authored", "doc"] && index == 3 && parent is JsonObject)
            return new JsonObject { ["type"] = "object" };
        if (path is ["puzzles", _, "authored", _] && index == 3 && parent is JsonObject)
            return new JsonObject();
        return parent?["properties"]?[path[index]];
    }

    private static bool HasLockedChildren(JsonNode node) => node switch
    {
        JsonObject obj => obj.ContainsKey("const") || obj.Any(pair => pair.Value is not null && HasLockedChildren(pair.Value)),
        JsonArray array => array.Any(item => item is not null && HasLockedChildren(item)),
        _ => false
    };

    public static JsonObject Schema(JsonObject source, IReadOnlyList<string[]> paths)
    {
        var schema = EmptyObject();
        foreach (var path in paths)
        {
            JsonObject from = source, into = schema;
            foreach (var (key, index) in path.Select((key, index) => (key, index)))
            {
                from = ChildSchema(from, path, index)!.AsObject();
                var properties = into["properties"]!.AsObject();
                if (properties[key] is null)
                {
                    properties[key] = index == path.Length - 1 ? from.DeepClone() : EmptyObject();
                    into["required"]!.AsArray().Add(key);
                }
                into = properties[key]!.AsObject();
            }
        }
        return schema;
    }

    private static JsonObject EmptyObject() => new()
    {
        ["type"] = "object", ["properties"] = new JsonObject(),
        ["required"] = new JsonArray(), ["additionalProperties"] = false
    };

    public static string Merge(string baselineJson, string patchJson, IReadOnlyList<string[]> paths)
    {
        var baseline = JsonNode.Parse(baselineJson)!.AsObject();
        var patch = JsonNode.Parse(patchJson)!.AsObject();
        foreach (var path in paths)
        {
            JsonNode target = baseline, changes = patch;
            foreach (var segment in path.SkipLast(1))
            {
                target = target[segment] ?? (target[segment] = new JsonObject())!;
                changes = changes[segment]!;
            }
            target[path[^1]] = changes[path[^1]]?.DeepClone();
        }
        return baseline.ToJsonString();
    }
}
